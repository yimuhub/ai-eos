"""共享的提示词片段。

上游模型（尤其是兼容网关）被问到身份时会自称模型或厂商名（实测 Agnes
会回答"我是 Agnes"）。对老板而言这家公司只有「员工」，模型名属于泄露
基础设施，也直接破坏人设的一致性，所以在人设提示里统一压住。
"""
from __future__ import annotations


def staff_identity(name: str) -> str:
    return (f"身份约束：你只以「{name}」这个公司身份出现。"
            "被问到你是谁、用什么模型时，回答自己是本公司的数字员工；"
            "不要提模型名、厂商名或网关名。")
